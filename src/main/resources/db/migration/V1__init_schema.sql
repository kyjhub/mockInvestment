-- 적용된 마이그레이션을 고치면 체크섬이 달라져 Flyway가 기동을 거부한다.
--
-- 스키마의 주인은 이 디렉터리다. 애플리케이션은 ddl-auto=validate로 엔티티와 테이블이 맞는지만 확인한다.

create sequence ledger_entries_seq start with 1 increment by 50;

create sequence ledger_transactions_seq start with 1 increment by 50;

create table account_funding_requests (
    asset_before_reset numeric(19,2) not null,
    profit_before_reset numeric(19,2) not null,
    requested_amount numeric(19,2) not null,
    return_rate_before_reset numeric(10,6) not null,
    round_no integer not null,
    account_id bigint not null,
    id bigint generated by default as identity,
    requested_at timestamp(6) not null,
    primary key (id),
    unique (account_id, round_no),
    check (round_no > 0 and requested_amount >= 1000 and requested_amount <= 100000)
);

create table account_resets (
    cumulative_profit_amount_before_reset numeric(19,2) not null,
    cumulative_requested_amount_before_reset numeric(19,2) not null,
    cumulative_return_rate_before_reset numeric(10,6) not null,
    account_id bigint not null,
    id bigint generated by default as identity,
    reset_at timestamp(6) not null,
    primary key (id)
);

create table accounts (
    cash_balance numeric(19,2) not null,
    current_round integer not null,
    initial_balance numeric(19,2) not null,
    realized_profit numeric(19,2) not null,
    total_asset_value numeric(19,2) not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    user_id bigint not null unique,
    status varchar(20) not null check (status in ('ACTIVE','SUSPENDED','CLOSED')),
    account_number varchar(30) not null unique,
    primary key (id),
    check (current_round > 0 and cash_balance >= 0)
);

create table daily_account_snapshots (
    cash_balance numeric(19,2) not null,
    realized_profit numeric(19,2) not null,
    return_rate numeric(10,6) not null,
    snapshot_date date not null,
    stock_evaluation numeric(19,2) not null,
    total_asset numeric(19,2) not null,
    unrealized_profit numeric(19,2) not null,
    account_id bigint not null,
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    primary key (id),
    unique (account_id, snapshot_date)
);

create table exchange_rates (
    basis_point numeric(19,6) not null,
    mid_rate numeric(19,6) not null,
    rate numeric(19,6) not null,
    id bigint generated by default as identity,
    valid_from timestamp(6) with time zone not null,
    valid_until timestamp(6) with time zone not null,
    base_currency varchar(10) not null check (base_currency in ('USD','KRW')),
    quote_currency varchar(10) not null check (quote_currency in ('USD','KRW')),
    rate_change_type varchar(20) not null check (rate_change_type in ('UP','DOWN','EVEN')),
    primary key (id),
    unique (base_currency, quote_currency, valid_from)
);

create table executions (
    commission numeric(19,2) not null,
    execution_price numeric(19,4) not null,
    tax numeric(19,2) not null,
    executed_at timestamp(6) not null,
    execution_quantity bigint not null,
    id bigint generated by default as identity,
    ledger_transaction_id bigint,
    order_id bigint not null,
    trade_id varchar(36),
    primary key (id)
);

create table holdings (
    average_price numeric(19,4) not null,
    total_purchase_amount numeric(19,2) not null,
    account_id bigint not null,
    id bigint generated by default as identity,
    quantity bigint not null,
    stock_id bigint not null,
    updated_at timestamp(6) not null,
    primary key (id),
    unique (account_id, stock_id),
    check (quantity >= 0 and total_purchase_amount >= 0)
);

create table leaderboard_rankings (
    cumulative_profit_amount numeric(19,2) not null,
    cumulative_return_rate numeric(10,6) not null,
    rank_by_profit_amount integer not null,
    rank_by_return_rate integer not null,
    account_id bigint not null,
    calculated_at timestamp(6) not null,
    primary key (account_id)
);

create table ledger_entries (
    amount numeric(19,2) not null,
    balance_after numeric(19,2),
    account_id bigint not null,
    created_at timestamp(6) not null,
    id bigint not null,
    quantity bigint,
    stock_id bigint,
    transaction_id bigint not null,
    ledger_account varchar(30) not null check (ledger_account in ('CASH','SECURITIES','REALIZED_PNL','FEE','TAX','EQUITY_FUNDING')),
    primary key (id)
);

create table ledger_transactions (
    id bigint not null,
    occurred_at timestamp(6) not null,
    reversal_of_id bigint,
    transaction_type varchar(30) not null check (transaction_type in ('ACCOUNT_OPENING','FUNDING','TRADE','FEE','ADJUSTMENT','RESET')),
    idempotency_key varchar(100) not null unique,
    description varchar(255),
    primary key (id)
);

create table orders (
    charged_commission numeric(19,2) default 0 not null,
    charged_tax numeric(19,2) default 0 not null,
    filled_amount numeric(19,4) default 0 not null,
    order_price numeric(19,4),
    reserved_unit_price numeric(19,4),
    account_id bigint not null,
    canceled_at timestamp(6),
    filled_quantity bigint not null,
    id bigint generated by default as identity,
    order_quantity bigint not null,
    rejected_at timestamp(6),
    remaining_quantity bigint not null,
    stock_id bigint not null,
    submitted_at timestamp(6) not null,
    updated_at timestamp(6) not null,
    order_side varchar(10) not null check (order_side in ('BUY','SELL')),
    order_type varchar(20) not null check (order_type in ('MARKET','LIMIT')),
    status varchar(20) not null check (status in ('AWAITING_PRICE','PENDING','PARTIALLY_FILLED','FILLED','CANCELED','REJECTED','EXPIRED')),
    client_order_id varchar(36),
    close_reason varchar(255),
    primary key (id),
    unique (account_id, client_order_id),
    check (order_quantity > 0 and filled_quantity >= 0 and remaining_quantity >= 0 and filled_quantity + remaining_quantity = order_quantity)
);

create table refresh_tokens (
    created_at timestamp(6) not null,
    expires_at timestamp(6) not null,
    id bigint generated by default as identity,
    revoked_at timestamp(6),
    user_id bigint not null,
    token_hash varchar(255) not null,
    primary key (id)
);

create table stock_korean_market_details (
    krx_trading_suspended boolean not null,
    liquidation_trading boolean not null,
    nxt_supported boolean not null,
    nxt_trading_suspended boolean not null,
    stock_id bigint not null,
    primary key (stock_id)
);

create table stock_prices (
    current_price numeric(19,4) not null,
    high_price numeric(19,4),
    low_price numeric(19,4),
    open_price numeric(19,4),
    previous_close numeric(19,4),
    id bigint generated by default as identity,
    received_at timestamp(6) not null,
    stock_id bigint not null,
    volume bigint,
    primary key (id)
);

create table stocks (
    delist_date date,
    is_common_share boolean not null,
    leverage_factor numeric(10,4),
    list_date date,
    id bigint generated by default as identity,
    shares_outstanding bigint,
    currency varchar(10) not null,
    isin_code varchar(20) unique,
    status varchar(20) not null check (status in ('ACTIVE','HALTED','DELISTED')),
    symbol varchar(20) not null unique,
    market varchar(30) not null check (market in ('KOSPI','KOSDAQ','KONEX','NASDAQ','NYSE','AMEX')),
    security_type varchar(30) not null check (security_type in ('STOCK','ETF','ETN')),
    english_name varchar(100),
    name varchar(100) not null,
    primary key (id)
);

create table users (
    created_at timestamp(6) not null,
    id bigint generated by default as identity,
    updated_at timestamp(6) not null,
    nickname varchar(50) not null unique,
    email varchar(255) not null unique,
    password_hash varchar(255) not null,
    role varchar(255) not null check (role in ('USER','ADMIN')),
    status varchar(255) not null check (status in ('ACTIVE','SUSPENDED','WITHDRAWN')),
    primary key (id)
);

create index idx_ledger_entries_account
