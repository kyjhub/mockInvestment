-- 테스트 전용 테이블. 운영 스키마(db/migration)에는 들어가지 않는다.
--
-- 벤치마크용 엔티티(BenchLedgerTransaction, BenchLedgerEntry)가 테스트 클래스패스에 있어서, 통합 테스트와
-- 벤치마크의 Spring context가 이들을 함께 스캔한다. ddl-auto=validate가 통과하려면 테이블이 있어야 한다.
--
-- 버전 번호가 없는 반복 마이그레이션(R__)이다. 버전을 붙이면, 재사용되는 벤치마크 DB에서 나중에 추가되는
-- 운영 마이그레이션(V2, V3...)이 "이미 적용된 버전보다 낮다"며 거부된다. 반복 마이그레이션은 모든 버전
-- 마이그레이션 뒤에, 내용이 바뀔 때만 다시 실행되므로 if not exists로 멱등하게 쓴다.
--
-- 원장 기본키를 SEQUENCE로 바꾸기 전 구조의 대조군이라 IDENTITY다(docs/load-test-candidates.md ④).

create table if not exists bench_ledger_transactions (
    id bigint generated by default as identity,
    transaction_type varchar(30) not null,
    idempotency_key varchar(100) not null unique,
    occurred_at timestamp(6) not null,
    description varchar(255),
    primary key (id)
);

create table if not exists bench_ledger_entries (
    id bigint generated by default as identity,
    transaction_id bigint not null references bench_ledger_transactions,
    account_id bigint not null references accounts,
    ledger_account varchar(30) not null,
    stock_id bigint references stocks,
    amount numeric(19,2) not null,
    quantity bigint,
    balance_after numeric(19,2),
    created_at timestamp(6) not null,
    primary key (id)
);

create index if not exists idx_bench_ledger_entries_account on bench_ledger_entries (account_id, ledger_account);
create index if not exists idx_bench_ledger_entries_transaction on bench_ledger_entries (transaction_id);
